class AgenticWorkflowReward(ORM):
    """
    Agentic RAG reward model aligned with the current COG/PLAN data format.
    It keeps Validator/Responder scoring from the original environment and rewrites
    Cognition + Planner rewards to match meta_info fields generated by the dataset pipeline.
    """

    def __init__(self, *args, **kwargs):
        self.parse_error_penalty = -2.0
        self.executor = concurrent.futures.ThreadPoolExecutor(max_workers=16)

    # =========================
    # 0. basic parsing / safety
    # =========================
    def _check_format(self, json_str: str, required_keys: set) -> Dict:
        data = parse_json(json_str)
        if not data or not isinstance(data, dict):
            return None
        if not required_keys.issubset(data.keys()):
            return None
        return data

    def calculate_leaky_tanh_reward(
        self,
        sim: float,
        threshold: float,
        k: float = 5.0,
        alpha: float = 0.5,
        gamma: float = 0.2,
    ) -> float:
        sim = max(0.0, min(1.0, float(sim or 0.0)))
        return alpha * math.tanh(k * (sim - threshold)) + gamma * sim

    def _safe_int(self, value, default: int) -> int:
        try:
            return int(value)
        except Exception:
            return default

    def _safe_float(self, value, default: float = 0.0) -> float:
        try:
            return float(value)
        except Exception:
            return default

    def _norm_modality(self, modality: str) -> str:
        m = str(modality or "").strip().lower()
        if m in {"text", "txt", "ocr", "document", "documents", "table", "tables"}:
            return "text"
        if m in {"image", "img", "visual", "vision", "page", "slide", "figure"}:
            return "image"
        if m in {"both", "all", "text+image", "image+text", "multi", "multimodal"}:
            return "both"
        return m


    def _norm_decision(self, decision: Any) -> str:
        d = str(decision or "").strip().upper()
        mapping = {
            "REFERENCE_SUFFICIENT": "REFERENCE_SUFFICIENT",
            "SUFFICIENT": "REFERENCE_SUFFICIENT",
            "EVIDENCE_SUFFICIENT": "REFERENCE_SUFFICIENT",
            "FURTHER_SEARCH_NEEDED": "FURTHER_SEARCH_NEEDED",
            "INSUFFICIENT": "FURTHER_SEARCH_NEEDED",
            "SEARCH_NEEDED": "FURTHER_SEARCH_NEEDED",
            "NO_SEARCH_NEEDED": "NO_SEARCH_NEEDED",
            "DIRECT": "NO_SEARCH_NEEDED",
            "DIRECT_ANSWER": "NO_SEARCH_NEEDED",
        }
        return mapping.get(d, d)

    def _strip_asset_prefix(self, asset_id: Any) -> str:
        s = str(asset_id or "").strip()
        s = re.sub(r"^(text_|img_|image_)", "", s)
        return s

    def _key(self, modality: str, asset_id: Any) -> Tuple[str, str]:
        return (self._norm_modality(modality), self._strip_asset_prefix(asset_id))

    def _parse_gold_key(self, key: Any) -> Tuple[str, str]:
        """Parse 'image:xxx' / 'text:xxx' into tuple; fallback to ('text', key)."""
        if isinstance(key, (tuple, list)) and len(key) >= 2:
            return self._key(str(key[0]), key[1])
        s = str(key or "").strip()
        if ":" in s:
            mod, aid = s.split(":", 1)
            return self._key(mod, aid)
        return self._key("text", s)

    def _keys_from_list(self, values: Any) -> Set[Tuple[str, str]]:
        if not values:
            return set()
        if isinstance(values, str):
            values = [values]
        out = set()
        for v in values:
            k = self._parse_gold_key(v)
            if k[0] in {"text", "image"} and k[1]:
                out.add(k)
        return out

    def _build_gt_set(self, meta_info: Dict) -> Set[Tuple[str, str]]:
        required = self._keys_from_list(meta_info.get("required_gold_keys"))
        if required:
            return required
        gt_set = set()
        for tid in meta_info.get("gt_text_ids", []) or []:
            gt_set.add(self._key("text", tid))
        for iid in meta_info.get("gt_image_ids", []) or []:
            gt_set.add(self._key("image", iid))
        # tables are evaluated as textual evidence in current reward pipeline.
        for tbid in meta_info.get("gt_table_ids", []) or []:
            gt_set.add(self._key("text", tbid))
        return gt_set

    def _coverage_sets_from_meta(self, meta_info: Dict) -> Dict[str, Set[Tuple[str, str]]]:
        """Use dataset-provided modality-aware gold coverage if available."""
        return {
            "required": self._build_gt_set(meta_info),
            "current": self._keys_from_list(meta_info.get("current_covered_gold_keys")),
            "prior": self._keys_from_list(meta_info.get("prior_covered_gold_keys")),
            "total": self._keys_from_list(meta_info.get("total_covered_gold_keys")),
        }

    def _build_source_map(self, meta_info: Dict) -> Dict[str, Dict[str, Any]]:
        """Build source_id -> {clean_id, modality, is_gt} map for both S1-A* and S0-A*."""
        source_map: Dict[str, Dict[str, Any]] = {}

        # New evidence pool ids: S1-A*
        for sid, minfo in (meta_info.get("short_to_original_map", {}) or {}).items():
            if isinstance(minfo, dict):
                clean_id = minfo.get("clean_id", "")
                modality = self._norm_modality(minfo.get("modality", "text"))
                is_gt = bool(minfo.get("is_gt", minfo.get("oracle_injected", False)))
            else:
                clean_id = minfo
                modality = "text"
                is_gt = False
            if clean_id and modality in {"text", "image"}:
                source_map[str(sid)] = {
                    "clean_id": self._strip_asset_prefix(clean_id),
                    "modality": modality,
                    "is_gt": is_gt,
                }

        # Accumulated belief source ids: S0-A*
        for item in meta_info.get("accumulated_belief_meta", []) or []:
            if not isinstance(item, dict):
                continue
            sid = str(item.get("source_id", "")).strip()
            clean_id = item.get("origin_asset_id", "")
            modality = self._norm_modality(item.get("modality", "text"))
            if sid and clean_id and modality in {"text", "image"}:
                source_map[sid] = {
                    "clean_id": self._strip_asset_prefix(clean_id),
                    "modality": modality,
                    "is_gt": bool(item.get("is_gt", False)),
                }
        return source_map

    def _source_ids_from_obj(self, obj: Any) -> Set[str]:
        return set(re.findall(r"S\d+-A\d+", str(obj or "")))

    def _map_sids_to_keys(self, sid_iterable, source_map: Dict[str, Dict[str, Any]]) -> Set[Tuple[str, str]]:
        out = set()
        for sid in sid_iterable:
            if sid in source_map:
                minfo = source_map[sid]
                key = self._key(minfo.get("modality", "text"), minfo.get("clean_id", ""))
                if key[0] in {"text", "image"} and key[1]:
                    out.add(key)
        return out

    def _parse_accumulated_source_ids(self, last_user_msg: str) -> Set[str]:
        """Parse source ids from Accumulated Belief State in prompt."""
        sids = set()
        if not last_user_msg:
            return sids
        m = re.search(r"Accumulated Belief State:\s*(\[.*?\])\s*(?:\n-|\n\n|$)", last_user_msg, re.DOTALL)
        if m:
            try:
                import json_repair
                arr = json_repair.loads(m.group(1))
                if isinstance(arr, list):
                    for b in arr:
                        if isinstance(b, dict):
                            sids.update(self._source_ids_from_obj(b.get("source_id", "")))
            except Exception:
                sids.update(self._source_ids_from_obj(m.group(1)))
        return sids

    def _parse_pool_source_ids(self, last_user_msg: str) -> Set[str]:
        if not last_user_msg:
            return set()
        pool_split = last_user_msg.split("NEW Evidence Pool:")
        pool_text = pool_split[-1] if len(pool_split) > 1 else ""
        return self._source_ids_from_obj(pool_text)

    # =========================
    # 1. history parsing helpers
    # =========================
    def _history_evals(self, meta_info: Dict) -> List[Dict[str, Any]]:
        vals = meta_info.get("historical_search_evaluations", [])
        return vals if isinstance(vals, list) else []

    def _count_search_attempts(self, meta_info: Dict, last_user_msg: str) -> int:
        """Prefer structured history; fallback to robust regex."""
        hist = self._history_evals(meta_info)
        if hist:
            return len(hist)
        if not last_user_msg:
            return 0
        patterns = [
            r"\[STEP\s*\d+\]\s*(?:TEXT|IMAGE|BOTH)\s*\(Top-\d+\)\s*:\s*.+",
            r"\[Step\s*\d+\]\s*(?:TEXT|IMAGE|BOTH).*?[:：]\s*['\"]?.+",
        ]
        count = 0
        for pat in patterns:
            matches = re.findall(pat, last_user_msg, flags=re.IGNORECASE)
            count = max(count, len(matches))
        return count

    def _parse_history_queries(self, meta_info: Dict, last_user_msg: str):
        """Return modality-specific historical queries. Structured meta first, regex fallback."""
        hist_text_queries, hist_image_queries = [], []
        for ev in self._history_evals(meta_info):
            if not isinstance(ev, dict):
                continue
            q = str(ev.get("query", "")).strip()
            m = self._norm_modality(ev.get("modality", ""))
            if not q:
                continue
            if m in {"text", "both"}:
                hist_text_queries.append(q)
            if m in {"image", "both"}:
                hist_image_queries.append(q)
        if hist_text_queries or hist_image_queries:
            return hist_text_queries, hist_image_queries

        if not last_user_msg:
            return hist_text_queries, hist_image_queries
        patterns = [
            r"\[STEP\s*\d+\]\s*(TEXT|IMAGE|BOTH)\s*\(Top-\d+\)\s*:\s*(.+?)(?=\n\[STEP|\n\n|$)",
            r"\[Step\s*\d+\]\s*(TEXT|IMAGE|BOTH).*?[:：]\s*['\"]?(.+?)['\"]?(?=\n\[Step|\n\n|$)",
        ]
        for pat in patterns:
            for mod, q in re.findall(pat, last_user_msg, flags=re.IGNORECASE | re.DOTALL):
                q_clean = str(q).strip().strip("'\"")
                if not q_clean:
                    continue
                m = self._norm_modality(mod)
                if m in {"text", "both"}:
                    hist_text_queries.append(q_clean)
                if m in {"image", "both"}:
                    hist_image_queries.append(q_clean)
        return hist_text_queries, hist_image_queries

    def _history_failure_stats(self, meta_info: Dict, last_user_msg: str) -> Dict[str, Any]:
        """Summarize whether previous retrieval has been exhausted/noisy."""
        hist = self._history_evals(meta_info)
        attempts = len(hist) if hist else self._count_search_attempts(meta_info, last_user_msg)
        failed = 0
        any_required_hits = 0
        missing_target_hits = 0
        if hist:
            for ev in hist:
                if not isinstance(ev, dict):
                    continue
                outcome = str(ev.get("outcome", "")).upper()
                if outcome in {"FAILED_OR_NOISY", "FAILED", "NOISY", "NO_HIT", "EMPTY"}:
                    failed += 1
                any_required_hits += len(ev.get("hits_any_required", []) or [])
                missing_target_hits += len(ev.get("hits_missing_target", []) or [])
        else:
            # If only prompt logs exist, be conservative: attempts known, failures unknown.
            failed = 0
        return {
            "attempts": attempts,
            "failed": failed,
            "failed_ratio": (failed / attempts) if attempts > 0 and hist else 0.0,
            "any_required_hits": any_required_hits,
            "missing_target_hits": missing_target_hits,
            "has_structured": bool(hist),
        }

    def _oracle_next_empty(self, meta_info: Dict) -> bool:
        cands = meta_info.get("oracle_next_query_candidates", None)
        return isinstance(cands, list) and len(cands) == 0

    def _allow_empty_planner_stop(self, meta_info: Dict, last_user_msg: str) -> bool:
        """Planner may output [] only when retrieval has been repeatedly exhausted."""
        stats = self._history_failure_stats(meta_info, last_user_msg)
        min_attempts = self._safe_int(meta_info.get("no_search_min_attempts", 3), 3)
        oracle_empty = self._oracle_next_empty(meta_info)

        # Structured history makes the decision much safer.
        if stats["has_structured"]:
            mostly_failed = stats["failed_ratio"] >= 0.60
            no_missing_hits = stats["missing_target_hits"] == 0
            return stats["attempts"] >= min_attempts and oracle_empty and mostly_failed and no_missing_hits

        # Fallback: allow only if prompt shows sufficient attempts and the oracle field explicitly says no candidate.
        return stats["attempts"] >= min_attempts and oracle_empty

    def _get_toolbox_safe(self, dataset_type: str):
        try:
            return get_toolbox(dataset_type)  # from reward_utils if available
        except Exception:
            return Toolbox(dataset_type)

    def _extract_gap_text(self, meta_info: Dict, last_user_msg: str) -> str:
        targets = meta_info.get("identified_information_targets", None)
        if isinstance(targets, list) and targets:
            return " ".join(str(g.get("description", "")) for g in targets if isinstance(g, dict)).strip()

        gap_match = re.search(
            r"Identified Information Targets:\s*(\[.*?\])(?=\n-|\Z)",
            last_user_msg or "",
            re.DOTALL | re.IGNORECASE,
        )
        if gap_match:
            try:
                import json_repair
                gaps = json_repair.loads(gap_match.group(1))
                if isinstance(gaps, list):
                    return " ".join(str(g.get("description", "")) for g in gaps if isinstance(g, dict)).strip()
            except Exception:
                desc_matches = re.findall(r'"description"\s*:\s*"([^"]+)"', gap_match.group(1))
                return " ".join(desc_matches).strip()
        return ""

    # =========================
    # 2. Cognition reward
    # =========================
    def score_cognition_step1(self, think: str, json_str: str, gt_dec: str, meta_info: Dict, last_user_msg: str) -> float:
        pred_data = self._check_format(
            json_str,
            {"decision", "belief_state", "dataset_vibe_analysis", "missing_info_gaps"},
        )
        if not pred_data:
            return -0.5

        task_score = 0.1
        source_map = self._build_source_map(meta_info)
        gt_set = self._build_gt_set(meta_info)
        coverage = self._coverage_sets_from_meta(meta_info)
        gt_answer_text = str(meta_info.get("gt_answer", ""))

        beliefs = pred_data.get("belief_state", [])
        gaps = pred_data.get("missing_info_gaps", [])
        if not isinstance(beliefs, list):
            beliefs = []
        if not isinstance(gaps, list):
            gaps = []

        # Current output belief source ids: allow both S0-A* and S1-A*.
        curr_sids = set()
        for b in beliefs:
            if isinstance(b, dict):
                curr_sids.update(self._source_ids_from_obj(b.get("source_id", "")))
        curr_mapped = self._map_sids_to_keys(curr_sids, source_map)

        # Available evidence: prefer total_covered/current_covered fields; fallback to source ids visible in prompt.
        total_covered = coverage["total"]
        current_covered = coverage["current"]
        if total_covered:
            available_gts = total_covered.intersection(gt_set)
        else:
            hist_sids = self._parse_accumulated_source_ids(last_user_msg)
            pool_sids = self._parse_pool_source_ids(last_user_msg)
            available_mapped = self._map_sids_to_keys(hist_sids.union(pool_sids), source_map)
            available_gts = available_mapped.intersection(gt_set)

        if current_covered:
            current_visible_gts = current_covered.intersection(gt_set)
        else:
            pool_sids = self._parse_pool_source_ids(last_user_msg)
            current_visible_gts = self._map_sids_to_keys(pool_sids, source_map).intersection(gt_set)

        curr_gold_hits = curr_mapped.intersection(gt_set)
        curr_available_hits = curr_mapped.intersection(available_gts)

        # valid/invalid sources must use combined source map, not only S1 short_to_original_map.
        valid_source_count = len(curr_sids.intersection(set(source_map.keys())))
        invalid_source_count = max(0, len(curr_sids) - valid_source_count)

        # -------------------------
        # A. belief extraction score
        # -------------------------
        if len(available_gts) > 0:
            if len(curr_mapped) == 0:
                extracted_score = -0.50
            else:
                recall = len(curr_available_hits) / len(available_gts)
                precision = len(curr_available_hits) / len(curr_mapped)
                f1_score = (2 * precision * recall / (precision + recall)) if (precision + recall) > 0 else 0.0
                extracted_score = self.calculate_leaky_tanh_reward(f1_score, threshold=0.65, k=5.0)
        else:
            extracted_score = 0.70 if len(curr_mapped) == 0 else -0.08 * len(curr_mapped)

        ideal_belief_count = max(1, len(available_gts)) if available_gts else 0
        over_extract_count = max(0, len(curr_mapped) - ideal_belief_count) if ideal_belief_count else 0
        source_valid_bonus = min(0.18, 0.03 * valid_source_count)
        invalid_source_penalty = 0.12 * invalid_source_count
        over_extract_penalty = 0.08 * (over_extract_count ** 2)
        belief_quality_score = source_valid_bonus - invalid_source_penalty - over_extract_penalty

        # -------------------------
        # B. decision score
        # -------------------------
        pred_dec = self._norm_decision(pred_data.get("decision", ""))
        beliefs_text = " ".join([str(b.get("fact", "")) for b in beliefs if isinstance(b, dict)]) if beliefs else " "
        gaps_text = " ".join([str(g.get("description", "")) for g in gaps if isinstance(g, dict)]) if gaps else " "
        answer_sim = calculate_text_similarity(beliefs_text, gt_answer_text) if gt_answer_text and beliefs_text.strip() else 0.0

        total_gold = len(gt_set)
        available_gold_coverage = (len(available_gts) / total_gold) if total_gold else 0.0
        curr_gold_coverage = (len(curr_gold_hits) / total_gold) if total_gold else 0.0
        extracted_recall = (len(curr_available_hits) / len(available_gts)) if available_gts else 0.0

        # Ground-truth decision from explicit label if present; otherwise infer from gold_status/coverage.
        # The data-generation pipeline supplies reliable cognition labels, so explicit labels are trusted.
        gt_dec_clean = self._norm_decision(gt_dec)
        if gt_dec_clean not in {"REFERENCE_SUFFICIENT", "FURTHER_SEARCH_NEEDED", "NO_SEARCH_NEEDED"}:
            gold_status = str(meta_info.get("gold_status", "")).upper()
            if (total_gold > 0 and available_gold_coverage >= 0.95) or gold_status == "ALL":
                gt_dec_clean = "REFERENCE_SUFFICIENT"
            elif self._allow_empty_planner_stop(meta_info, last_user_msg):
                gt_dec_clean = "NO_SEARCH_NEEDED"
            else:
                gt_dec_clean = "FURTHER_SEARCH_NEEDED"

        decision_score = 0.0
        is_gold_sufficient = (gt_dec_clean == "REFERENCE_SUFFICIENT") or (total_gold > 0 and available_gold_coverage >= 0.95)
        is_gold_no_search = (gt_dec_clean == "NO_SEARCH_NEEDED") or self._allow_empty_planner_stop(meta_info, last_user_msg)

        if pred_dec == "REFERENCE_SUFFICIENT":
            # Correct when explicit label or coverage says evidence is sufficient; belief extraction is scored separately.
            if is_gold_sufficient:
                evidence_score = self.calculate_leaky_tanh_reward(max(curr_gold_coverage, extracted_recall), threshold=0.50, k=5.0)
                decision_score = 0.45 + evidence_score + 0.12 * answer_sim
                if gaps:
                    decision_score -= min(0.60, 0.15 * len(gaps))
            else:
                # Premature sufficiency.
                decision_score = -0.55
                if gaps:
                    decision_score += min(0.10, 0.03 * len(gaps))

        elif pred_dec == "FURTHER_SEARCH_NEEDED":
            if is_gold_sufficient:
                # Evidence already sufficient; continuing is unnecessary.
                decision_score = -0.45 if extracted_recall >= 0.50 or answer_sim >= 0.50 else -0.15
            elif is_gold_no_search:
                # Search already exhausted; further search should be weaker than NO_SEARCH_NEEDED.
                decision_score = -0.20
            else:
                redundant_penalty = 0.0
                max_sim = 0.0
                try:
                    dataset_type = meta_info.get("dataset_type")
                    toolbox = self._get_toolbox_safe(dataset_type)
                    missing_gts = gt_set - available_gts
                    unfound_text_ids = [aid for mod, aid in missing_gts if mod == "text"]
                    unfound_image_ids = [aid for mod, aid in missing_gts if mod == "image"]

                    # Prefer explicit unfound ids if present.
                    if meta_info.get("unfound_text_ids") is not None:
                        unfound_text_ids = [self._strip_asset_prefix(x) for x in meta_info.get("unfound_text_ids", [])]
                    if meta_info.get("unfound_image_ids") is not None:
                        unfound_image_ids = [self._strip_asset_prefix(x) for x in meta_info.get("unfound_image_ids", [])]

                    needs_text = len(unfound_text_ids) > 0
                    needs_image = len(unfound_image_ids) > 0
                    best_text_rr = 0.0
                    best_img_rr = 0.0

                    for g in gaps:
                        if not isinstance(g, dict):
                            continue
                        gap_text = str(g.get("description", "")).strip()
                        gap_mod = self._norm_modality(g.get("suggested_modality", ""))
                        if not gap_text:
                            continue
                        if gap_mod == "both":
                            if not (needs_text and needs_image):
                                redundant_penalty += 0.30
                        elif gap_mod == "text" and not needs_text:
                            redundant_penalty += 0.30
                        elif gap_mod == "image" and not needs_image:
                            redundant_penalty += 0.30
                        elif gap_mod not in {"text", "image", "both"}:
                            redundant_penalty += 0.20

                        if gap_mod in {"text", "both"} and unfound_text_ids:
                            best_text_rr = max(best_text_rr, toolbox.calculate_text_sim(gap_text, unfound_text_ids))
                        if gap_mod in {"image", "both"} and unfound_image_ids:
                            best_img_rr = max(best_img_rr, toolbox.calculate_image_sim(gap_text, unfound_image_ids))
                    max_sim = max(best_text_rr, best_img_rr)
                except Exception as e:
                    logger.warning(f"⚠️ Gap ToolBox Eval Failed (Fallback): {e}")
                    if gt_answer_text:
                        max_sim = calculate_text_similarity(gaps_text, gt_answer_text)

                gap_tendency = self.calculate_leaky_tanh_reward(max_sim, threshold=0.40, k=5.0)
                if not gaps:
                    redundant_penalty += 0.20
                decision_score = gap_tendency - redundant_penalty

        elif pred_dec == "NO_SEARCH_NEEDED":
            # Fallback state: allowed only after repeated failed retrieval or explicit NO_SEARCH_NEEDED label.
            if is_gold_sufficient:
                decision_score = -0.45
            elif is_gold_no_search:
                stats = self._history_failure_stats(meta_info, last_user_msg)
                gap_penalty = min(0.30, 0.08 * len(gaps))
                exhaustion_bonus = min(0.15, 0.03 * max(0, stats["attempts"] - self._safe_int(meta_info.get("no_search_min_attempts", 3), 3)))
                # Moderate reward: below successful sufficient, but above blind further search.
                decision_score = 0.30 + exhaustion_bonus - gap_penalty
            else:
                decision_score = -0.45
        else:
            decision_score = -0.50

        final_score = task_score + decision_score + extracted_score + belief_quality_score
        logger.info(
            f"🎯 Cognition Final: {final_score:.2f} | Dec:{pred_dec} GT:{gt_dec_clean} | "
            f"Task:{task_score:.2f} DecScore:{decision_score:.2f} Extr:{extracted_score:.2f} "
            f"BeliefQ:{belief_quality_score:.2f} | AvailGT:{len(available_gts)}/{len(gt_set)} "
            f"CurrGT:{len(curr_gold_hits)} | Sources valid/invalid:{valid_source_count}/{invalid_source_count} "
            f"Attempts:{self._count_search_attempts(meta_info, last_user_msg)}"
        )
        return final_score

    # =========================
    # 3. Planner reward
    # =========================
    def _evaluate_planner_single(self, completion: str, meta_info: dict, last_user_msg: str) -> float:
        think, json_str, _ = extract_think_and_json(completion)
        pred_data = self._check_format(json_str, {"next_search_actions"})
        if not pred_data:
            return 0.0

        task_score = 0.1
        actions = pred_data.get("next_search_actions", [])

        unfound_text_ids = set(self._strip_asset_prefix(x) for x in meta_info.get("unfound_text_ids", []) or [])
        unfound_image_ids = set(self._strip_asset_prefix(x) for x in meta_info.get("unfound_image_ids", []) or [])
        needs_text = len(unfound_text_ids) > 0
        needs_image = len(unfound_image_ids) > 0

        # Case C: no missing target left -> empty action is correct.
        if not needs_text and not needs_image:
            if isinstance(actions, list) and len(actions) == 0:
                return 1.50
            return -0.70

        # Case B: missing evidence remains, but repeated searches failed and no oracle next query exists.
        if isinstance(actions, list) and len(actions) == 0:
            if self._allow_empty_planner_stop(meta_info, last_user_msg):
                stats = self._history_failure_stats(meta_info, last_user_msg)
                # Moderate positive reward, not higher than successful evidence hit.
                return 0.35 + min(0.12, 0.03 * max(0, stats["attempts"] - 3))
            return -0.60

        if not isinstance(actions, list):
            return -0.60

        try:
            toolbox = Toolbox(meta_info.get("dataset_type"))
        except Exception as e:
            logger.warning(f"Toolbox init failed: {e}")
            return task_score

        gap_text = self._extract_gap_text(meta_info, last_user_msg)
        hist_text_queries, hist_image_queries = self._parse_history_queries(meta_info, last_user_msg)

        global_found_text_ids = set()
        global_found_image_ids = set()
        text_top_n_cost = 0
        image_top_n_cost = 0
        wasted_top_n_cost = 0
        total_top_n = 0

        cumulative_mrr = 0.0
        redundant_penalty = 0.0
        lazy_copy_penalty = 0.0
        soft_exploration_bonus = 0.0
        best_query_target_sim = 0.0
        dead_action_penalty = 0.0
        invalid_action_penalty = 0.0
        valid_action_count = 0

        try:
            for action in actions:
                if not isinstance(action, dict):
                    invalid_action_penalty += 0.25
                    continue

                query = str(action.get("query", "")).strip()
                modality = self._norm_modality(action.get("modality", ""))
                top_n = max(1, min(self._safe_int(action.get("top_n", 3), 3), 10))

                if not query:
                    invalid_action_penalty += 0.25
                    continue
                if modality not in {"text", "image", "both"}:
                    invalid_action_penalty += 0.40
                    continue

                valid_action_count += 1
                total_top_n += top_n
                action_new_hits = 0
                action_targets_needed = False
                action_best_target_sim = 0.0

                # Same-modality repetition penalty.
                relevant_hist_sims = [0.0]
                if modality in {"text", "both"} and hist_text_queries:
                    relevant_hist_sims.append(max(calculate_text_similarity(query, hq) for hq in hist_text_queries))
                if modality in {"image", "both"} and hist_image_queries:
                    relevant_hist_sims.append(max(calculate_text_similarity(query, hq) for hq in hist_image_queries))
                max_hist_sim = max(relevant_hist_sims)
                if max_hist_sim > 0.90:
                    redundant_penalty += 0.35 * math.tanh(6.0 * (max_hist_sim - 0.90))

                # Do not punish normal query rewriting; only punish near-copying a long gap description.
                if gap_text:
                    sim_to_gap = calculate_text_similarity(query, gap_text)
                    if sim_to_gap > 0.96 and len(query) > 60 and len(gap_text) > 80:
                        lazy_copy_penalty += 0.12 * math.tanh(10.0 * (sim_to_gap - 0.96))
                    elif sim_to_gap > 0.20:
                        soft_exploration_bonus = max(soft_exploration_bonus, 0.04 * sim_to_gap)

                declares_text = modality in {"text", "both"}
                declares_image = modality in {"image", "both"}

                # Wrong modality and unnecessary both must bear actual wasted-cost penalty.
                if declares_text and not needs_text:
                    wasted_top_n_cost += top_n
                    redundant_penalty += 0.45 if modality == "text" else 0.30
                if declares_image and not needs_image:
                    wasted_top_n_cost += top_n
                    redundant_penalty += 0.45 if modality == "image" else 0.30
                if modality == "both" and not (needs_text and needs_image):
                    redundant_penalty += 0.20

                # Semantic target similarity is only shaping, not a substitute for hit.
                if declares_text and needs_text:
                    action_targets_needed = True
                    action_best_target_sim = max(action_best_target_sim, toolbox.calculate_text_sim(query, list(unfound_text_ids)))
                if declares_image and needs_image:
                    action_targets_needed = True
                    action_best_target_sim = max(action_best_target_sim, toolbox.calculate_image_sim(query, list(unfound_image_ids)))
                best_query_target_sim = max(best_query_target_sim, action_best_target_sim)

                if declares_text and needs_text:
                    text_top_n_cost += top_n
                    res = toolbox.text_search(query, top_n=top_n)
                    r_ids = [self._strip_asset_prefix(r.get("asset_id", "")) for r in res]
                    for rank, tid in enumerate(r_ids):
                        if tid in unfound_text_ids and tid not in global_found_text_ids:
                            cumulative_mrr += 1.0 / math.sqrt(rank + 1)
                            global_found_text_ids.add(tid)
                            action_new_hits += 1

                if declares_image and needs_image:
                    image_top_n_cost += top_n
                    res = toolbox.image_search(query, top_n=top_n)
                    r_ids = [self._strip_asset_prefix(r.get("asset_id", "")) for r in res]
                    for rank, iid in enumerate(r_ids):
                        if iid in unfound_image_ids and iid not in global_found_image_ids:
                            cumulative_mrr += 1.0 / math.sqrt(rank + 1)
                            global_found_image_ids.add(iid)
                            action_new_hits += 1

                if action_targets_needed and action_new_hits == 0:
                    # If query direction is good but retriever misses, penalty is small; otherwise larger.
                    dead_action_penalty += 0.10 * (1.0 - min(1.0, action_best_target_sim))
        except Exception as e:
            logger.warning(f"Action Search Failed: {e}")

        def _dynamic_beta(unfound_count: int) -> float:
            if unfound_count <= 1:
                return 0.7
            if unfound_count <= 3:
                return 1.0
            return 1.3

        def _budgeted_f_score(found_count: int, unfound_count: int, top_n_cost: int):
            if unfound_count <= 0:
                return 0.0, 0.0, 1.0, 0.0, 0
            beta = _dynamic_beta(unfound_count)
            recall = found_count / unfound_count
            expected_budget = min(6, max(3, unfound_count * 2))
            effective_cost = max(top_n_cost, expected_budget)
            precision = found_count / effective_cost if effective_cost > 0 else 0.0
            denom = (beta ** 2) * precision + recall
            f_score = ((1 + beta ** 2) * precision * recall / denom) if denom > 0 else 0.0
            over_budget = max(0, top_n_cost - expected_budget)
            return f_score, precision, recall, beta, over_budget

        text_f1 = text_precision = text_recall = text_beta = 0.0
        text_over_budget = 0
        if needs_text:
            text_f1, text_precision, text_recall, text_beta, text_over_budget = _budgeted_f_score(
                len(global_found_text_ids), len(unfound_text_ids), text_top_n_cost
            )

        img_f1 = img_precision = img_recall = img_beta = 0.0
        img_over_budget = 0
        if needs_image:
            img_f1, img_precision, img_recall, img_beta, img_over_budget = _budgeted_f_score(
                len(global_found_image_ids), len(unfound_image_ids), image_top_n_cost
            )

        active_modalities   = int(needs_text) + int(needs_image)
        avg_f1 = (text_f1 + img_f1) / active_modalities if active_modalities > 0 else 0.0

        structural_reward = 1.25 * avg_f1
        rank_reward = 0.25 * math.tanh(0.4 * cumulative_mrr)
        total_found = len(global_found_text_ids) + len(global_found_image_ids)

        if total_found == 0:
            # No evidence hit should not receive high positive reward.
            final_planner_reward = -0.15 + 0.12 * best_query_target_sim + min(0.04, soft_exploration_bonus)
        else:
            final_planner_reward = structural_reward + rank_reward + 0.08 * best_query_target_sim

        modal_over_budget = text_over_budget + img_over_budget
        cost_penalty = 0.03 * pow(modal_over_budget, 2) + 0.02 * pow(wasted_top_n_cost, 2)
        action_count_penalty = 0.05 * max(0, valid_action_count - 2)
        total_penalty = (
            redundant_penalty
            + lazy_copy_penalty
            + cost_penalty
            + dead_action_penalty
            + action_count_penalty
            + invalid_action_penalty
        )
        final_score = task_score + final_planner_reward - total_penalty

        logger.info(
            f"🎯 Planner Final: {final_score:.2f} | "
            f"TF{text_beta:.1f}:{text_f1:.2f}(P:{text_precision:.2f},R:{text_recall:.2f}) | "
            f"IF{img_beta:.1f}:{img_f1:.2f}(P:{img_precision:.2f},R:{img_recall:.2f}) | "
            f"AvgF:{avg_f1:.2f} Hits:{total_found} Sem:{best_query_target_sim:.2f} MRR:{rank_reward:.2f} | "
            f"Pen:-{total_penalty:.2f} Red:-{redundant_penalty:.2f} Copy:-{lazy_copy_penalty:.2f} "
            f"Dead:-{dead_action_penalty:.2f} Cost:-{cost_penalty:.2f} Invalid:-{invalid_action_penalty:.2f} "
            f"WastedTopN:{wasted_top_n_cost} HistQ:{len(hist_text_queries)+len(hist_image_queries)}"
        )
        return final_score

    # =========================
    # 4. role routing
    # =========================
    def __call__(self, completions, **kwargs):
        messages_batch = kwargs.get('messages', [])
        ground_truths = kwargs.get('ground_truth', [])
        meta_infos_raw = kwargs.get('meta_info', [])

        final_scores = [0.0] * len(completions)
        assigned_roles = [""] * len(completions)
        planner_indices, planner_tasks = [], []

        for i, completion in enumerate(completions):
            think, json_str, _ = extract_think_and_json(completion)
            try:
                last_user_msg = next((m['content'] for m in reversed(messages_batch[i]) if m['role'] == 'user'), "")
            except Exception:
                last_user_msg = ""

            role = "Responder"
            if "Role: High-Recall Auditor" in last_user_msg:
                role = "Validator"
            elif "Role: Cognitive Orchestrator" in last_user_msg:
                role = "Cognition"
            elif "Role: Expert Search Engineer" in last_user_msg:
                role = "Planner"
            assigned_roles[i] = role

            gt_val = ground_truths[i] if i < len(ground_truths) else ""
            try:
                meta_raw = meta_infos_raw[i] if i < len(meta_infos_raw) else {}
                meta_data = json.loads(meta_raw) if isinstance(meta_raw, str) else (meta_raw or {})
            except Exception:
                meta_data = {}

            if role == "Validator":
                gt_dict = json.loads(gt_val) if isinstance(gt_val, str) and gt_val.strip().startswith("{") else gt_val
                final_scores[i] = self.score_validator(think, json_str, gt_dict if isinstance(gt_dict, dict) else {})
            elif role == "Cognition":
                final_scores[i] = self.score_cognition_step1(think, json_str, str(gt_val), meta_data, last_user_msg)
            elif role == "Planner":
                planner_indices.append(i)
                planner_tasks.append((completion, meta_data, last_user_msg))
            elif role == "Responder":
                final_scores[i] = self.score_final(think, json_str, str(gt_val))

        if planner_tasks:
            results = list(self.executor.map(lambda p: self._evaluate_planner_single(p[0], p[1], p[2]), planner_tasks))
            for idx, score in zip(planner_indices, results):
                final_scores[idx] = score

        return final_scores


